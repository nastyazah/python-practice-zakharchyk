first_number = float(input("Enter the first number: "))
second_number = float(input("Enter the second number: "))

sum_result = first_number + second_number
difference_result = first_number - second_number
product_result = first_number * second_number
quotient_result = first_number / second_number
floor_division_result = first_number // second_number
remainder_result = first_number % second_number
power_result = first_number ** second_number

print(f"{first_number} + {second_number} = {sum_result}")
print(f"{first_number} - {second_number} = {difference_result}")
print(f"{first_number} * {second_number} = {product_result}")
print(f"{first_number} / {second_number} = {quotient_result}")
print(f"{first_number} // {second_number} = {floor_division_result}")
print(f"{first_number} % {second_number} = {remainder_result}")
print(f"{first_number} ** {second_number} = {power_result}")
